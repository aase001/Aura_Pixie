def load_app_icon() -> QIcon:
    """从内存解码 PNG -> QIcon；失败返回空图标（调用方回退文件资源）。"""
    try:
        pm = QPixmap()
        if pm.loadFromData(base64.b64decode(_ICON_PNG_BASE64)):
            icon = QIcon(pm)
            if not icon.isNull():
                return icon
    except Exception:
        pass
    return QIcon()
